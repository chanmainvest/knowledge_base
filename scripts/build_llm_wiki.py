# A valid Yahoo-style symbol (used to decide whether a prediction's topic
# page is keyed by ticker or by asset/company name).
SYMBOL_RE = re.compile(r"^[A-Z0-9^.=:\-]{1,12}(\.[A-Z]{1,4})?$")


def _topic_key(p: dict) -> str | None:
    """Page key for a prediction row: the Yahoo symbol when the ticker is
    symbol-like, otherwise the asset/company name (LLMs sometimes emit
    asset-name fragments like 'PAN MINE' into the ticker field; the extract
    pipeline nulls those tickers, so name-keyed grouping picks them up)."""
    tk = (p.get("ticker") or "").strip().upper()
    if tk and SYMBOL_RE.match(tk):
        return tk
    name = (p.get("asset_name") or tk or "").strip()
    return name or None


def topic_page_file(key: str) -> str:
    """Filename (without .md) for a topic page: symbols are used as-is
    (keeps existing pages like ^TNX.md stable), names are slugified."""
    return key if SYMBOL_RE.match(key) else slugify(key)


def group_predictions_by_ticker(preds: list[dict]) -> dict[str, list[dict]]:
    g: dict[str, list[dict]] = defaultdict(list)
    for p in preds:
        k = _topic_key(p)
        if k:
            g[k].append(p)
    return g


def _theme_match(hay: str, keywords: list[str]) -> bool:
    """True if any keyword matches the haystack. Keywords ending in a
    non-word char (e.g. 'gold ') are treated as substring matches; bare
    alphabetic keywords are matched as whole-word tokens (so 'gold' does
    not catch 'Goldman'). Tickers / codes and non-ASCII (CJK) keywords are
    matched as substrings."""
    h = hay.lower()
    for kw in keywords:
        k = kw.lower()
        if not k.isascii():
            # CJK: \b word boundaries don't fire between CJK chars
            if k in h:
                return True
        elif k[-1:] in " =-." or not k.isalpha():
            # codes/tickers contain non-alphanumerics or trailing space → substring
            if k in h:
                return True
        else:
            # whole-word match for plain words
            if re.search(rf"\b{re.escape(k)}\b", h):
                return True
    return False


def ticker_themes(ticker: str, asset_name: str) -> list[str]:
    """Return theme slugs a ticker belongs to."""
    hay = f"{ticker} {asset_name or ''}"
    return [t["slug"] for t in THEMES if _theme_match(hay, t["keywords"])]


def view_themes(v: dict) -> list[str]:
    """Theme slugs a market view belongs to (matched on its text)."""
    hay = " ".join(str(v.get(k) or "") for k in
                   ("asset_class", "region", "rationale", "quote"))
    return [t["slug"] for t in THEMES if _theme_match(hay, t["keywords"])]


def views_for_theme(theme_slug: str) -> list[dict]:
    return [v for v in DATA["views"] if theme_slug in view_themes(v)]


def preds_for_theme(theme_slug: str) -> list[dict]:
    out = []
    for p in DATA["preds"]:
        hay = f"{p.get('ticker','')} {p.get('asset_name','')}"
        if _theme_match(hay, next(t["keywords"] for t in THEMES
                                  if t["slug"] == theme_slug)):
            out.append(p)
    return out


