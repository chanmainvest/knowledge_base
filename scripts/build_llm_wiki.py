def main() -> None:
    global DATA, PEOPLE, TOPICS
    ap = argparse.ArgumentParser(
        description="Build the llm-wiki from the knowledge database.")
    ap.add_argument("--no-bios", action="store_true",
                    help="skip LLM bio generation for People pages")
    ap.add_argument("--provider", default=None,
                    help="LLM provider for bios (default: LLM_PROVIDER, "
                         "i.e. the configured zai/GLM default)")
    ap.add_argument("--model", default=None,
                    help=f"LLM model for bios (zai default: {WIKI_ZAI_MODEL}; "
                         "other providers: their configured default)")
    args = ap.parse_args()

    print("loading data from DB …")
    DATA = fetch_all()
    print(f"  {len(DATA['preds'])} predictions, {len(DATA['views'])} views, "
          f"{len(DATA['analysts'])} channels with extractions, "
          f"{len(DATA['item_speakers'])} items with speaker lists")

    print("building people registry …")
    PEOPLE = build_people()
    n_multi = sum(1 for p in PEOPLE.values() if len(p["channels"]) > 1)
    print(f"  {len(PEOPLE)} people "
          f"({n_multi} appearing on more than one show)")

    bios = ensure_bios(no_llm=args.no_bios, provider=args.provider,
                       model=args.model)
    print(f"  bios cached/generated: {len(bios)}")

    TOPICS = build_topic_matrix()

    # Incremental build: the tree is never wiped. Pages are written (or
    # left as-is when unchanged) by the renderers; afterwards, pages a
    # previous run generated that this run no longer produces are removed
    # via the manifest. Anything else living in llm-wiki/ is untouched.
    WIKI_DIR.mkdir(parents=True, exist_ok=True)

    pages: dict[str, list[tuple[str, str]]] = {
        "People": [], "Tickers": [], "Analysts": [], "Themes": [],
        "Syntheses": []}

    # --- People ---
    for name in sorted(PEOPLE):
        person = PEOPLE[name]
        if not (person["appearances"] or person["n_events"]):
            continue
        render_person(person, bios)
        pages["People"].append((person["slug"], name))

    # --- Tickers ---
    by_tk = group_predictions_by_ticker(DATA["preds"])
    for tk, plist in sorted(by_tk.items()):
        p = render_ticker(tk, plist)
        if p:
            asset_name = next((pp.get("asset_name") for pp in plist
                               if pp.get("asset_name")), tk)
            label = (f"{tk} — {asset_name}" if SYMBOL_RE.match(tk)
                     and asset_name != tk else tk)
            pages["Tickers"].append((topic_page_file(tk), label))

    # --- Analysts ---
    for a in DATA["analysts"]:
        render_analyst(a)
        pages["Analysts"].append(
            (channel_slug(a), a.get("channel_name") or a.get("channel_handle") or "?"))

    # --- Themes ---
    for theme in THEMES:
        # only emit a theme page if it has any preds or views
        if preds_for_theme(theme["slug"]) or views_for_theme(theme["slug"]):
            render_theme(theme)
            pages["Themes"].append((theme["slug"], theme["title"]))

    # --- Syntheses ---
    render_opinion_shifts()
    pages["Syntheses"].append(
        ("Opinion-Shifts", "Opinion Shifts (same person changes mind)"))
    render_disagreements()
    pages["Syntheses"].append(
        ("Disagreements", "Disagreements (people vs people)"))
    render_timeline()
    pages["Syntheses"].append(("Timeline", "Timeline of Calls (global)"))

    # --- Home, Index, README, AGENTS ---
    counts = {k: len(v) for k, v in pages.items()}
    render_home(DATA, counts)
    render_index(pages)
    render_readme(DATA, counts)
    render_agents()

    # --- garbage-collect pages that no longer exist ----------------------
    prev: set[str] = set()
    if MANIFEST.exists():
        try:
            prev = set(json.loads(MANIFEST.read_text(encoding="utf-8")))
        except Exception:  # noqa: BLE001 — corrupt manifest: just skip GC
            prev = set()
    removed = 0
    for rel in sorted(prev - WRITTEN):
        p = WIKI_DIR / rel
        if p.exists():
            p.unlink()
            print(f"  removed stale page: {rel}")
            removed += 1
    # prune directories the removals may have emptied (bottom-up)
    for d in sorted((p for p in WIKI_DIR.rglob("*") if p.is_dir()),
                    reverse=True):
        try:
            d.rmdir()
        except OSError:
            pass
    MANIFEST.write_text(json.dumps(sorted(WRITTEN), indent=0) + "\n",
                        encoding="utf-8")

    print(f"\nwiki written to {WIKI_DIR} "
          f"({len(WRITTEN)} pages, {removed} stale removed)")
    for k in ("People", "Tickers", "Analysts", "Themes", "Syntheses"):
        print(f"  {k:<10} {counts[k]}")


if __name__ == "__main__":
    main()
